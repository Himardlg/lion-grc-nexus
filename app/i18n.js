  const phrases = Object.keys(translations)
    .sort((a, b) => b.length - a.length);

  function isEnglish() {
    try {
      return window.db?.settings?.language === 'en';
    } catch (_) {
      return false;
    }
  }

  function translate(value) {
    if (typeof value !== 'string' || !value || !isEnglish()) {
      return value;
    }

    const trimmed = value.trim();

    if (Object.prototype.hasOwnProperty.call(translations, trimmed)) {
      return value.replace(trimmed, translations[trimmed]);
    }

    let result = value;

    for (const phrase of phrases) {
      if (result.includes(phrase)) {
        result = result.split(phrase).join(translations[phrase]);
      }
    }

    return result;
  }

  const attributes = [
    'placeholder',
    'title',
    'aria-label',
    'alt'
  ];

  function visit(node) {
    if (node.nodeType === Node.TEXT_NODE) {
      const parent = node.parentElement;

      if (
        parent &&
        ['SCRIPT', 'STYLE', 'TEXTAREA'].includes(parent.tagName)
      ) {
        return;
      }

      const translated = translate(node.nodeValue);

      if (translated !== node.nodeValue) {
        node.nodeValue = translated;
      }

      return;
    }

    if (
      node.nodeType !== Node.ELEMENT_NODE ||
      ['SCRIPT', 'STYLE'].includes(node.tagName)
    ) {
      return;
    }

    for (const attribute of attributes) {
      const value = node.getAttribute(attribute);

      if (value) {
        const translated = translate(value);

        if (translated !== value) {
          node.setAttribute(attribute, translated);
        }
      }
    }

    if (
      node.tagName === 'INPUT' &&
      ['button', 'submit'].includes(node.type)
    ) {
      const translated = translate(node.value);

      if (translated !== node.value) {
        node.value = translated;
      }
    }

    for (const child of Array.from(node.childNodes)) {
      visit(child);
    }
  }

  function applyLanguage() {
    if (!document.body) return;

    if (!isEnglish()) {
      document.documentElement.lang = 'es';
      return;
    }

    visit(document.body);
    document.documentElement.lang = 'en';
  }

  let scheduled = false;

  function scheduleTranslation() {
    if (scheduled) return;

    scheduled = true;

    queueMicrotask(() => {
      scheduled = false;
      applyLanguage();
    });
  }

  function start() {
    applyLanguage();

    if (typeof MutationObserver !== 'undefined') {
      const observer = new MutationObserver(scheduleTranslation);

      observer.observe(document.body, {
        subtree: true,
        childList: true,
        characterData: true,
        attributes: true,
        attributeFilter: attributes
      });
    }
  }

  window.nexusTranslate = translate;
  window.nexusApplyLanguage = applyLanguage;

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', start, { once: true });
  } else {
    start();
  }

  window.addEventListener('languagechange', applyLanguage);
